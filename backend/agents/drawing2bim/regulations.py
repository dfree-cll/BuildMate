def build_regulation_context(include_codes: list[str] | None = None) -> str:
    """生成规范上下文文本（默认全量；可指定规范编码子集）"""
    regs = REGULATIONS
    if include_codes:
        regs = [r for r in regs if r["code"] in include_codes]
    if not regs:
        return ""
    blocks = []
    for r in regs:
        pts = "\n".join(f"  - {p}" for p in r["points"])
        blocks.append(f"《{r['code']} {r['title']}》要点：\n{pts}")
    return "\n\n".join(blocks)
